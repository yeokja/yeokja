"""Check the built Korean site against an English build of the pinned upstream.

Usage (inside the project devShell, from the project directory):

    python3 scripts/check_site.py dist/site [--reference DIR]

Without `--reference`, the English original is built from `upstream/` into
`build/reference/` through the same `scripts/prepare.py` patch the Korean build
uses, so the two sites differ only in the translated text.

Checks, per HTML page:
  * the page set is identical;
  * section anchors (`<section id>`) are identical and in the same order
    (scripts/en_anchors.py keeps English anchors on translated headings);
  * the numbers of headings (h1-h6), figures, tables, images, numbered
    captions and math blocks are identical;
  * every local link and asset (`href`/`src` without a scheme) resolves to a
    file in the site, and every `#fragment` exists as an `id` in its target;
  * no Google Analytics script survives, and the translation notice is shown.

Prints one sorted line per problem and exits non-zero if there is any.
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
from collections import Counter
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import unquote, urlsplit

PROJECT = Path(__file__).resolve().parents[1]
NOTICE = "비공식 기계 번역"
# Pages generated by Sphinx itself or by the theme rather than from the book.
SKIP_COUNT_PAGES = {"genindex.html", "search.html"}


class PageParser(HTMLParser):
    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.ids: set[str] = set()
        self.sections: list[str] = []
        self.counts: Counter[str] = Counter()
        self.links: list[str] = []
        self.scripts: list[str] = []

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        attributes = {name: value or "" for name, value in attrs}
        if "id" in attributes:
            self.ids.add(attributes["id"])
        if tag == "a" and "name" in attributes:
            self.ids.add(attributes["name"])
        if tag == "section" and "id" in attributes:
            self.sections.append(attributes["id"])
        if tag in {"h1", "h2", "h3", "h4", "h5", "h6", "figure", "table", "img"}:
            self.counts[tag] += 1
        classes = attributes.get("class", "").split()
        if tag == "span" and "caption-number" in classes:
            self.counts["caption-number"] += 1
        if tag == "div" and "math" in classes:
            self.counts["math-block"] += 1
        if tag == "script" and attributes.get("src"):
            self.scripts.append(attributes["src"])
        for name in ("href", "src"):
            if attributes.get(name):
                self.links.append(attributes[name])

    def handle_data(self, data: str) -> None:
        if "gtag(" in data:
            self.scripts.append("inline gtag()")


def parse(path: Path) -> PageParser:
    parser = PageParser()
    parser.feed(path.read_text(encoding="utf-8"))
    return parser


def pages(site: Path) -> dict[str, Path]:
    return {
        path.relative_to(site).as_posix(): path
        for path in site.rglob("*.html")
        if not path.relative_to(site).parts[0].startswith(("_static", "_sources", "_images"))
    }


def build_reference(out: Path) -> Path:
    source = PROJECT / "build" / "reference-src"
    shutil.rmtree(source, ignore_errors=True)
    shutil.rmtree(out, ignore_errors=True)
    shutil.copytree(PROJECT / "upstream", source, ignore=shutil.ignore_patterns(".git", "_build"))
    env = dict(os.environ, YEOKJA_ROOT=str(PROJECT))
    subprocess.run([sys.executable, str(PROJECT / "scripts" / "prepare.py"), str(source)], check=True)
    subprocess.run(
        [sys.executable, "-m", "sphinx", "-b", "html", "-q", "--fail-on-warning", ".", str(out)],
        cwd=source,
        env=env,
        check=True,
    )
    return out


def check(site: Path, reference: Path) -> list[str]:
    problems: list[str] = []
    ko_pages, en_pages = pages(site), pages(reference)
    for name in sorted(en_pages.keys() - ko_pages.keys()):
        problems.append(f"{name}: page missing from Korean site")
    for name in sorted(ko_pages.keys() - en_pages.keys()):
        problems.append(f"{name}: page not in English reference")

    parsed = {name: parse(path) for name, path in ko_pages.items()}
    for name in sorted(ko_pages.keys() & en_pages.keys()):
        ko, en = parsed[name], parse(en_pages[name])
        if ko.sections != en.sections:
            missing = [i for i in en.sections if i not in ko.sections]
            problems.append(f"{name}: section anchors differ (missing {missing[:5]})")
        if name not in SKIP_COUNT_PAGES:
            for key in sorted(en.counts.keys() | ko.counts.keys()):
                if en.counts[key] != ko.counts[key]:
                    problems.append(f"{name}: {key} count {ko.counts[key]} != original {en.counts[key]}")

    for name, page in sorted(parsed.items()):
        for script in page.scripts:
            if "googletagmanager" in script or "gtag" in script:
                problems.append(f"{name}: analytics script {script}")
        if name not in {"search.html"} and NOTICE not in ko_pages[name].read_text(encoding="utf-8"):
            problems.append(f"{name}: translation notice missing")
        base = ko_pages[name].parent
        for link in page.links:
            parts = urlsplit(link)
            if parts.scheme or parts.netloc or link.startswith(("mailto:", "javascript:", "data:")):
                continue
            target_name = name
            if parts.path:
                target = (base / unquote(parts.path)).resolve()
                if target.is_dir():
                    target = target / "index.html"
                if not target.exists():
                    problems.append(f"{name}: broken link {link}")
                    continue
                try:
                    target_name = target.relative_to(site.resolve()).as_posix()
                except ValueError:
                    problems.append(f"{name}: link leaves the site {link}")
                    continue
            fragment = unquote(parts.fragment)
            if fragment and target_name in parsed and fragment not in parsed[target_name].ids:
                problems.append(f"{name}: missing anchor {link}")
    return sorted(set(problems))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("site", type=Path)
    parser.add_argument("--reference", type=Path)
    args = parser.parse_args(argv)
    reference = args.reference or build_reference(PROJECT / "build" / "reference")
    problems = check(args.site.resolve(), reference.resolve())
    for problem in problems:
        print(problem)
    print(f"checked {len(pages(args.site))} pages: {len(problems)} problem(s)", file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
